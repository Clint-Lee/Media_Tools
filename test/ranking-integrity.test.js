'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),os=require('os'),path=require('path');
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'hotpot-integrity-'));
process.env.HOTPOT_SOURCE_CACHE=path.join(directory,'sources');process.env.HOTPOT_COLLECTION_DIR=path.join(directory,'collection');
const {prepareVideoList}=require('../lib/video-pipeline'),{videoDataQuality}=require('../lib/data-quality');
const ranking=require('../public/ranking'),{createIndex}=require('../lib/collection-index');
const list=[{id:'a',title:'上海播放视频',platform:'youtube',playRaw:50,likeRaw:0},{id:'b',title:'东京高赞视频',platform:'youtube',playRaw:2,likeRaw:100},{id:'c',title:'播放未知',platform:'youtube',playRaw:null,likeRaw:999}].map(v=>({...v,pubdate:Math.floor(Date.now()/1000),fetchedAt:Date.now()}));
assert.deepEqual(prepareVideoList(list).map(v=>v.id),['a','b','c']);
assert.deepEqual(prepareVideoList(list,{sortBy:'likes'}).map(v=>v.id),['c','b','a']);
assert.equal(ranking.summary(list,'views').ranked,2);assert.equal(ranking.summary(list,'likes').ranked,3);
assert.equal(videoDataQuality([list[2]]).status,'metadata-only','只有点赞不能把播放覆盖标为ready');
assert.equal(videoDataQuality([list[2]],{sortBy:'likes'}).status,'ready');
const index=createIndex({directory:path.join(directory,'index')});
index.record('youtube',Array.from({length:35},(_,i)=>({...list[0],id:'video-'+i,playRaw:100-i,likeRaw:i})));
const first=index.query({platform:'youtube',sortBy:'likes'});
assert.equal(first.list[0].id,'video-34');assert.equal(first.ranking.metric,'likes');
assert.throws(()=>index.query({platform:'youtube',sortBy:'views',cursor:first.nextCursor}),/筛选不匹配/,'不能把点赞游标用于播放榜');
const adapters=require('../lib/platform-rankings'),original=adapters.youtubeApiVideos,sources=require('../lib/live-sources');
assert.equal(sources.biliVideo({bvid:'BV1xx411c7mD',title:'真实结构',stat:{view:123,like:9}},'fixture').likeRaw,9,'官方已返回的点赞不应丢弃');
process.env.YOUTUBE_API_KEY='isolated-fixture';
adapters.youtubeApiVideos=async options=>({list:prepareVideoList(options.page===1?[list[0]]:[list[0],list[1]]),message:'隔离来源',source:'fixture'});
(async()=>{
    const options={platform:'youtube',category:'all',timeRange:'all',query:'',scope:'available'};
    await sources.getVideos({...options,page:1});await sources.getVideos({...options,page:2});
    const geo=await sources.collectedGeoVideos(options);
    assert.equal(geo.list.length,2,'地球须统计所有已加载分页，并按作品去重');
    assert.equal(sources.aggregateGeo(geo.list).reduce((n,row)=>n+row.count,0),2);
    console.log('Ranking integrity passed: explicit metrics, zero counts, coverage, cursor binding and multi-page geo deduplication');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{adapters.youtubeApiVideos=original;await sources.closeBrowser();fs.rmSync(directory,{recursive:true,force:true});});
