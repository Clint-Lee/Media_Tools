'use strict';
const assert = require('node:assert/strict');
const path = require('path');
const fs = require('fs');
const puppeteer = require('puppeteer');
(async () => {
    const browser = await puppeteer.launch({headless:true,args:['--no-sandbox','--disable-setuid-sandbox']});
    const page = await browser.newPage();
    const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:4000';
    const auth=await require('./live-auth').liveAuth(base), pair=auth.cookie.split('=');
    await page.setCookie({name:pair[0],value:pair[1],url:base,httpOnly:true,sameSite:'Strict'});
    await page.setViewport({width:1440,height:1000});
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    const evidence=path.join(__dirname,'..','.cache','verification');
    fs.mkdirSync(evidence,{recursive:true});
    const ready = () => page.waitForFunction(()=>document.querySelector('#loader')?.classList.contains('hidden'),{timeout:90000});
    try {
        await page.goto(base,{waitUntil:'domcontentloaded'});
        await page.waitForSelector('#cards-grid .video-card',{timeout:90000});
        assert.equal(await page.$$eval('#cards-grid .video-card',cards=>cards.length),30,'首批渲染30个视频');
        console.log('Initial feed: 30 cards');
        await page.click('#cards-grid .video-card');
        await page.waitForSelector('#player-modal:not(.hidden)',{timeout:5000});
        assert.ok(await page.$('#modal-video-wrapper iframe'));
        await page.click('#close-player-modal-btn');
        await page.click('[data-category="pets"]');
        await page.click('[data-category="tech"]');
        await page.click('[data-time="3days"]');
        await ready();
        assert.equal(await page.$$eval('#cards-grid .video-card',cards=>cards.length),30);
        assert.equal(await page.$eval('.filter-chip.active',e=>e.dataset.category),'tech');
        assert.equal(await page.$eval('.time-chip.active',e=>e.dataset.time),'3days');
        assert.ok((await page.$eval('#source-status',e=>e.textContent)).includes('真实播放量'));
        await page.waitForFunction(()=>Array.from(document.querySelectorAll('#cards-grid .card-thumbnail')).slice(0,4).every(image=>image.complete && image.naturalWidth>0),{timeout:20000});
        await page.screenshot({path:path.join(evidence,'bilibili-3days.png')});
        await page.$eval('#grid-scroll-area',e=>{e.scrollTop=e.scrollHeight;});
        await page.waitForFunction(()=>document.querySelectorAll('#cards-grid .video-card').length>=60,{timeout:15000});
        console.log('Lazy load: 60 cards; rapid filters retained newest selection');
        await page.click('.view-switch-btn[data-view="globe"]');
        await page.waitForFunction(()=>document.querySelector('#geo-coverage')?.textContent.includes('样本'),{timeout:90000});
        assert.ok((await page.$eval('#geo-city-count',e=>e.textContent)) !== '48');
        await page.screenshot({path:path.join(evidence,'geo-samples.png')});
        await page.click('.view-switch-btn[data-view="feed"]');
        await page.click('[data-category="all"]');
        await page.click('#btn-metric-topic');
        await ready();
        await page.click('.nav-btn[data-platform="douyin"]');
        await ready();
        assert.ok(await page.$('#topics-grid .topic-event-card'));
        assert.ok((await page.$eval('#source-status',e=>e.textContent)).includes('官方排名'));
        console.log('Douyin official topic ranking displayed');
        await page.screenshot({path:path.join(evidence,'douyin-official-topics.png')});
        await page.click('#btn-nav-mediatools');
        await page.type('#mt-input-url','https://www.bilibili.com/video/BV1GGaZ6AEzJ');
        await page.click('#mt-extract-btn');
        await page.waitForSelector('#mt-bili-frame',{timeout:90000});
        await page.waitForFunction(()=>document.querySelector('#mt-analysis-status')?.textContent.startsWith('完成'),{timeout:300000});
        assert.ok(await page.$$eval('#mt-transcript-timeline .transcript-line-item',items=>items.length>0));
        assert.ok((await page.$eval('#mt-transcript-timeline',e=>e.textContent)).includes('手机壳'));
        await page.click('[data-mttab="ai"]');
        assert.ok(await page.$$eval('#mt-ai-hooks [data-seek]',items=>items.length>0));
        assert.ok((await page.$eval('#mt-ai-trigger',e=>e.textContent)).includes('手机壳'));
        await page.screenshot({path:path.join(evidence,'actual-content-analysis.png')});
        await page.click('#mt-ai-hooks [data-seek]');
        assert.ok((await page.$eval('#mt-bili-frame',e=>e.src)).includes('t='));
        assert.deepEqual(errors,[],'浏览器不得发生未处理的运行错误');
        console.log('Real transcript, grounded AI points and seek interaction passed');
        console.log('Browser UI checks passed. Evidence:',evidence);
    } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
