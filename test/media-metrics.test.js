'use strict';
const assert = require('node:assert/strict');
const { fromMetadata } = require('../lib/media-metrics');
const engine = require('../lib/yt-dlp-parser');
const at = 1700000000000;
let row = fromMetadata({ view_count: 123456789, like_count: '1234', comment_count: 0 }, { platform: 'youtube', at });
assert.equal(row.playRaw, 123456789);
assert.equal(row.likeRaw, 1234);
assert.equal(row.commentCount, 0);
assert.equal(row.viewsFetchedAt, at);
assert.equal(row.viewPrecision, 'integer');
row = fromMetadata({ like_count: 99999 }, { platform: 'douyin' });
assert.equal(row.playRaw, null, '真实点赞不能推算为播放');
assert.equal(row.likeRaw, 99999);
assert.equal(fromMetadata({ view_count: 0 }, { platform: 'douyin' }).viewEvidence.status, 'placeholder-zero');
assert.equal(fromMetadata({ view_count: 0 }, { platform: 'youtube' }).playRaw, 0);
row = fromMetadata({ view_count: 99999, like_count: 5 }, { platform: 'twitter' });
assert.equal(row.playRaw, null, 'yt-dlp Twitter 的帖子曝光不是视频播放');
assert.equal(row.postImpressionRaw, 99999);
assert.equal(row.likeRaw, 5);
assert.equal(fromMetadata({ view_count: 100 }, { platform: 'twitter', source: 'twitter:fxembed-video' }).playRaw, 100);
assert.equal(fromMetadata({ view_count: '1.2万' }).viewPrecision, 'source-rounded');
row = fromMetadata({ like_count: '10万+' }, { platform: 'xiaohongshu' });
assert.equal(row.likeRaw, null, '真实下界不是可排序的精确点赞');
assert.equal(row.likeLowerBound, 100000);
assert.equal(row.likePrecision, 'lower-bound');
assert.equal(fromMetadata({ view_count: 123, views_fetched_at: at }, { at: at + 5000 }).viewsFetchedAt, at, '提取器缓存中的计数不能伪造当前观测时间');
for (const value of [null, undefined, true, -1, Infinity, NaN, {}, 1.2]) assert.equal(fromMetadata({ view_count: value }).playRaw, null);
assert.deepEqual(engine.jsRuntimeArgs({ env: {}, version: '20.20.0', bundledExecutable: '' }), []);
assert.deepEqual(engine.jsRuntimeArgs({ env: {}, version: '24.0.0', executable: 'node-new' }), ['--js-runtimes', 'node:node-new']);
assert.deepEqual(engine.jsRuntimeArgs({ env: { YTDLP_JS_RUNTIME: 'deno:C:/with spaces/deno.exe' } }), ['--js-runtimes', 'deno:C:/with spaces/deno.exe']);
for (const value of ['https://node.test', 'node:x\n--exec bad', 'python', 'node\rfoo'])
    assert.throws(() => engine.jsRuntimeArgs({ env: { YTDLP_JS_RUNTIME: value } }), /YTDLP_JS_RUNTIME/);
assert.deepEqual(engine.proxyArgs('https://www.douyin.com/video/1', { MEDIA_PROXY: 'http://proxy.test:7897' }), ['--proxy', '']);
assert.deepEqual(engine.proxyArgs('https://www.youtube.com/watch?v=abc', { MEDIA_PROXY: 'http://proxy.test:7897' }), ['--proxy', 'http://proxy.test:7897']);
assert.deepEqual(engine.proxyArgs('https://www.youtube.com/watch?v=abc', {}), ['--proxy', '']);
const red = require('../lib/red-public');
assert.equal(red.videoUrl({ video: { consumer: { originVideoKey: 'spectrum/path/video.mp4' } } }), 'https://sns-video-bd.xhscdn.com/spectrum/path/video.mp4');
for (const key of ['../private', '/video.mp4', 'https://evil.test/video', 'path/%2e%2e/private', 'path//file'])
    assert.equal(red.videoUrl({ video: { consumer: { originVideoKey: key } } }), null);
console.log('Media metric provenance, runtime/proxy selection and XHS original-stream fallback passed');
